import math
import os
import requests


def query_prometheus(promql, datasource_id=1, timeout=5):
    base_url = os.environ["GRAFANA_BASE_URL"]
    auth = (os.environ["GRAFANA_USER"], os.environ["GRAFANA_PASSWORD"])
    resp = requests.get(
        f"{base_url}/api/datasources/proxy/{datasource_id}/api/v1/query",
        params={"query": promql},
        auth=auth,
        timeout=timeout,
    )
    resp.raise_for_status()
    return resp.json()


def _scalar(promql):
    result = query_prometheus(promql)
    return float(result["data"]["result"][0]["value"][1])


def _vector(promql):
    result = query_prometheus(promql)
    return result["data"]["result"]


def get_service_trace_metrics(window="30m"):
    """
    Uses Tempo span metrics (traces_spanmetrics_*) generated by the Tempo metrics generator.
    Covers all iot-core-* services via the 'service' label (not 'job').
    Latency unit: seconds (multiply by 1000 for ms).
    status_code='STATUS_CODE_ERROR' only appears when errors are actively traced.

    Returns None if Tempo span metrics are not scraped in Prometheus.
    """
    total_r = _vector(
        f'sum by(service)(rate(traces_spanmetrics_calls_total[{window}]))'
    )
    if not total_r:
        return None

    # Error spans — only present when errors occur; empty result means zero errors
    error_r = _vector(
        f'sum by(service)(rate(traces_spanmetrics_calls_total{{status_code="STATUS_CODE_ERROR"}}[{window}]))'
    )

    # P95 latency per service across all span kinds (seconds)
    p95_r = _vector(
        f'histogram_quantile(0.95,sum by(service,le)'
        f'(rate(traces_spanmetrics_latency_bucket[{window}])))'
    )

    call_rate_by_svc = {}
    for r in total_r:
        svc = r["metric"].get("service", "unknown")
        v = float(r["value"][1])
        if not math.isnan(v):
            call_rate_by_svc[svc] = round(v, 6)
    call_rate_by_svc = dict(sorted(call_rate_by_svc.items(), key=lambda x: x[1], reverse=True))

    error_rate_by_svc = {}
    for r in error_r:
        svc = r["metric"].get("service", "unknown")
        v = float(r["value"][1])
        if not math.isnan(v):
            error_rate_by_svc[svc] = round(v, 6)

    latency_p95_by_svc = {}
    for r in p95_r:
        svc = r["metric"].get("service", "unknown")
        v = _nan_to_none(float(r["value"][1]))
        if v is not None:
            latency_p95_by_svc[svc] = round(v * 1000, 3)  # convert to ms

    total_call_rate = sum(call_rate_by_svc.values())
    total_error_rate = sum(error_rate_by_svc.values())
    fleet_error_pct = (total_error_rate / total_call_rate * 100) if total_call_rate > 0 else 0.0

    if fleet_error_pct >= 2.0:
        level = "critical"
    elif fleet_error_pct >= 0.5:
        level = "warning"
    else:
        level = "good"

    return {
        "fleet_call_rate_per_sec": round(total_call_rate, 6),
        "fleet_error_rate_pct": round(fleet_error_pct, 4),
        "call_rate_by_service": call_rate_by_svc,
        "error_rate_by_service": error_rate_by_svc,
        "latency_p95_ms_by_service": latency_p95_by_svc,
        "level": level,
        "window": window,
    }


def get_java_error_rate(window="30m"):
    """Backward-compatible alias — delegates to get_service_trace_metrics."""
    return get_service_trace_metrics(window=window)


def _nan_to_none(v):
    return None if (v is None or math.isnan(v)) else v


def _per_service(results):
    """Convert a Prometheus vector result into {job: value} dict, sorted by value desc."""
    out = {}
    for r in results:
        job = r["metric"].get("job") or r["metric"].get("service_name", "unknown")
        v = float(r["value"][1])
        if not math.isnan(v):
            out[job] = round(v, 6)
    return dict(sorted(out.items(), key=lambda x: x[1], reverse=True))


def get_otel_service_metrics(job=".+", window="30m"):
    """
    All Prometheus panels from 'OpenTelemetry Metrics Dashboard (No Traces/Logs) 2'
    (uid=otlp-metrics-only-dashboard2):
      - HTTP: request rate, error rate %, latency P95 (per service + fleet total)
      - JVM: CPU utilization, heap %, non-heap %, thread count, GC time (per service)
      - DB (MongoDB/MySQL): operations rate, P50/P95/P99 duration (per service)
      - Cache (Redis): operations rate, P50/P95 duration (per service)

    Level thresholds (HTTP error rate, Bo_chi_so API Success Rate / Core):
      good < 0.5% | warning 0.5-2% | critical >= 2%
    """
    jf = f'job=~"{job}"'

    # ── HTTP ──────────────────────────────────────────────────────────────────
    http_count = (
        "http_server_request_duration_seconds_count"
        "|http_server_request_duration_count"
        "|http_server_duration_seconds_count"
        "|http_server_duration_count"
    )
    http_bucket = (
        "http_server_request_duration_seconds_bucket"
        "|http_server_request_duration_bucket"
        "|http_server_duration_seconds_bucket"
        "|http_server_duration_bucket"
    )

    total_r = _vector(f'sum by(job)(rate({{__name__=~"{http_count}",{jf}}}[{window}]))')
    error_5xx_r = _vector(
        f'sum by(job)(rate({{__name__=~"http_server_request_duration_seconds_count'
        f'|http_server_request_duration_count",{jf},'
        f'http_response_status_code=~"5.*"}}[{window}]))'
    )
    error_4xx_r = _vector(
        f'sum by(job)(rate({{__name__=~"http_server_request_duration_seconds_count'
        f'|http_server_request_duration_count",{jf},'
        f'http_response_status_code=~"4.*"}}[{window}]))'
    )
    latency_p50_r = _vector(
        f'histogram_quantile(0.50,sum by(job,le)'
        f'(rate({{__name__=~"{http_bucket}",{jf}}}[{window}])))'
    )
    latency_p95_r = _vector(
        f'histogram_quantile(0.95,sum by(job,le)'
        f'(rate({{__name__=~"{http_bucket}",{jf}}}[{window}])))'
    )
    latency_p99_r = _vector(
        f'histogram_quantile(0.99,sum by(job,le)'
        f'(rate({{__name__=~"{http_bucket}",{jf}}}[{window}])))'
    )

    total_by_svc = _per_service(total_r)
    error_by_svc = _per_service(error_5xx_r)
    error_4xx_by_svc = _per_service(error_4xx_r)

    def _latency_dict(vec):
        return {
            r["metric"].get("job", "unknown"): _nan_to_none(float(r["value"][1]))
            for r in vec
        }

    latency_p50_by_svc = _latency_dict(latency_p50_r)
    latency_p95_by_svc = _latency_dict(latency_p95_r)
    latency_p99_by_svc = _latency_dict(latency_p99_r)

    fleet_total = sum(total_by_svc.values())
    fleet_errors = sum(error_by_svc.values())
    fleet_4xx = sum(error_4xx_by_svc.values())
    fleet_error_pct = (fleet_errors / fleet_total * 100) if fleet_total > 0 else 0.0
    fleet_4xx_pct = (fleet_4xx / fleet_total * 100) if fleet_total > 0 else 0.0

    error_rate_pct_by_svc = {
        svc: round(error_by_svc.get(svc, 0) / total_by_svc[svc] * 100, 4)
        for svc in total_by_svc
        if total_by_svc[svc] > 0
    }

    if fleet_error_pct < 0.5:
        http_level = "good"
    elif fleet_error_pct < 2.0:
        http_level = "warning"
    else:
        http_level = "critical"

    # ── JVM ──────────────────────────────────────────────────────────────────
    jvm_cpu_r = _vector(f'jvm_cpu_recent_utilization_ratio{{{jf}}}')
    jvm_cpu = _per_service(jvm_cpu_r)

    heap_used_r = _vector(f'sum by(job)(jvm_memory_used_bytes{{{jf},jvm_memory_type="heap"}})')
    heap_max_r  = _vector(f'sum by(job)(jvm_memory_limit_bytes{{{jf},jvm_memory_type="heap"}})')
    heap_used = {r["metric"].get("job","?"): float(r["value"][1]) for r in heap_used_r}
    heap_max  = {r["metric"].get("job","?"): float(r["value"][1]) for r in heap_max_r}
    heap_pct  = {
        svc: round(heap_used[svc] / heap_max[svc] * 100, 2)
        for svc in heap_used if svc in heap_max and heap_max[svc] > 0
    }

    non_heap_used_r = _vector(f'sum by(job)(jvm_memory_used_bytes{{{jf},jvm_memory_type="non_heap"}})')
    non_heap_max_r  = _vector(f'sum by(job)(jvm_memory_limit_bytes{{{jf},jvm_memory_type="non_heap"}})')
    non_heap_used = {r["metric"].get("job","?"): float(r["value"][1]) for r in non_heap_used_r}
    non_heap_max  = {r["metric"].get("job","?"): float(r["value"][1]) for r in non_heap_max_r}
    non_heap_pct  = {
        svc: round(non_heap_used[svc] / non_heap_max[svc] * 100, 2)
        for svc in non_heap_used if svc in non_heap_max and non_heap_max[svc] > 0
    }

    thread_r = _vector(f'sum by(job)(jvm_thread_count{{{jf}}})')
    threads = _per_service(thread_r)

    gc_r = _vector(f'sum by(job)(rate(jvm_gc_duration_sum{{{jf}}}[{window}]))')
    gc_time = _per_service(gc_r)

    # ── DB (MongoDB / MySQL) ──────────────────────────────────────────────────
    db_f = f'{jf},db_system_name=~"mongodb|mysql"'
    db_ops_r = _vector(
        f'sum by(job)(rate(db_client_operation_duration_seconds_count{{{db_f}}}[{window}]))'
    )
    db_ops = _per_service(db_ops_r)

    db_p50_r = _vector(
        f'histogram_quantile(0.50,sum by(job,le)'
        f'(rate(db_client_operation_duration_seconds_bucket{{{db_f}}}[{window}])))'
    )
    db_p95_r = _vector(
        f'histogram_quantile(0.95,sum by(job,le)'
        f'(rate(db_client_operation_duration_seconds_bucket{{{db_f}}}[{window}])))'
    )
    db_p99_r = _vector(
        f'histogram_quantile(0.99,sum by(job,le)'
        f'(rate(db_client_operation_duration_seconds_bucket{{{db_f}}}[{window}])))'
    )
    db_p50 = {r["metric"].get("job","?"): _nan_to_none(float(r["value"][1])) for r in db_p50_r}
    db_p95 = {r["metric"].get("job","?"): _nan_to_none(float(r["value"][1])) for r in db_p95_r}
    db_p99 = {r["metric"].get("job","?"): _nan_to_none(float(r["value"][1])) for r in db_p99_r}

    # ── Cache (Redis) ─────────────────────────────────────────────────────────
    cache_f = f'{jf},db_system_name="redis"'
    cache_ops_r = _vector(
        f'sum by(job)(rate(db_client_operation_duration_seconds_count{{{cache_f}}}[{window}]))'
    )
    cache_ops = _per_service(cache_ops_r)

    cache_p50_r = _vector(
        f'histogram_quantile(0.50,sum by(job,le)'
        f'(rate(db_client_operation_duration_seconds_bucket{{{cache_f}}}[{window}])))'
    )
    cache_p95_r = _vector(
        f'histogram_quantile(0.95,sum by(job,le)'
        f'(rate(db_client_operation_duration_seconds_bucket{{{cache_f}}}[{window}])))'
    )
    cache_p50 = {r["metric"].get("job","?"): _nan_to_none(float(r["value"][1])) for r in cache_p50_r}
    cache_p95 = {r["metric"].get("job","?"): _nan_to_none(float(r["value"][1])) for r in cache_p95_r}

    return {
        "window": window,
        "http": {
            "fleet_request_rate_per_sec": round(fleet_total, 6),
            "fleet_error_rate_pct": round(fleet_error_pct, 4),
            "fleet_4xx_rate_pct": round(fleet_4xx_pct, 4),
            "request_rate_by_service": total_by_svc,
            "error_rate_by_service": error_by_svc,
            "error_4xx_by_service": error_4xx_by_svc,
            "error_rate_pct_by_service": error_rate_pct_by_svc,
            "latency_p50_sec_by_service": latency_p50_by_svc,
            "latency_p95_sec_by_service": latency_p95_by_svc,
            "latency_p99_sec_by_service": latency_p99_by_svc,
            "level": http_level,
        },
        "jvm": {
            "cpu_utilization_by_service": jvm_cpu,
            "heap_utilization_pct_by_service": heap_pct,
            "non_heap_utilization_pct_by_service": non_heap_pct,
            "thread_count_by_service": threads,
            "gc_time_rate_by_service": gc_time,
        },
        "db": {
            "operations_rate_per_sec_by_service": db_ops,
            "duration_p50_sec_by_service": db_p50,
            "duration_p95_sec_by_service": db_p95,
            "duration_p99_sec_by_service": db_p99,
        },
        "cache": {
            "operations_rate_per_sec_by_service": cache_ops,
            "duration_p50_sec_by_service": cache_p50,
            "duration_p95_sec_by_service": cache_p95,
        },
    }



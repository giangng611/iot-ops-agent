def query_loki(logql, limit=100, start=None, end=None, timeout=10):
    import time as _time
    base_url = os.environ["GRAFANA_BASE_URL"]
    auth = (os.environ["GRAFANA_USER"], os.environ["GRAFANA_PASSWORD"])
    now = int(_time.time())
    resp = requests.get(
        f"{base_url}/api/datasources/proxy/2/loki/api/v1/query_range",
        params={
            "query": logql,
            "limit": limit,
            "start": start if start is not None else (now - 3600),
            "end": end if end is not None else now,
        },
        auth=auth,
        timeout=timeout,
    )
    resp.raise_for_status()
    return resp.json()


def get_service_logs(service=".+", level="error", limit=20, hours_back=1):
    """
    Queries Loki (datasource id=2) for recent service logs.
    iot-core-* services export logs via OTel → use 'detected_level' label (e.g. error, warn, info).
    Linux journal logs use 'level' label instead. This function queries detected_level by default.
    label 'service_name' examples: iot-core-accounting-api, emqx, iot-core-devicemgmt
    """
    import time as _time
    logql = f'{{service_name=~"{service}", detected_level=~"{level}"}}'
    now = int(_time.time())
    result = query_loki(logql, limit=limit, start=now - hours_back * 3600, end=now)
    streams = result.get("data", {}).get("result", [])
    entries = []
    for stream in streams:
        svc = stream["stream"].get("service_name", "unknown")
        lvl = stream["stream"].get("detected_level") or stream["stream"].get("level", "unknown")
        for ts_ns, msg in stream.get("values", []):
            entries.append({
                "timestamp_ns": ts_ns,
                "service_name": svc,
                "level": lvl,
                "message": msg,
            })
    entries.sort(key=lambda e: e["timestamp_ns"], reverse=True)
    return {
        "service_filter": service,
        "level_filter": level,
        "hours_back": hours_back,
        "count": len(entries),
        "entries": entries[:limit],
    }


# ── Infrastructure health ─────────────────────────────────────────────────────


def get_emqx_health():
    """
    Combines EMQX main, client-events, and messages dashboards via Prometheus.
    Level driver: message drop rate (good < 0.1/s | warning 0.1-1.0/s | critical > 1.0/s).
    """
    connections_r = _vector("sum(emqx_connections_count)")
    connections = int(float(connections_r[0]["value"][1])) if connections_r else 0

    def _rate(metric):
        r = _vector(f"sum(rate({metric}[1m]))")
        return round(float(r[0]["value"][1]), 6) if r else 0.0

    recv_rate = _rate("emqx_messages_received_total")
    sent_rate = _rate("emqx_messages_sent_total")
    drop_rate = _rate("emqx_messages_dropped_total")
    auth_rate = _rate("emqx_client_authenticate_total")
    sub_rate = _rate("emqx_client_subscribe_total")

    disconn_r = _vector("sum by(reason)(rate(emqx_client_disconnected_total[1m]))")
    disconnects_by_reason = {
        r["metric"].get("reason", "unknown"): round(float(r["value"][1]), 6)
        for r in disconn_r
    }

    if drop_rate > 1.0:
        level = "critical"
    elif drop_rate > 0.1:
        level = "warning"
    else:
        level = "good"

    return {
        "connections": connections,
        "message_received_rate": recv_rate,
        "message_sent_rate": sent_rate,
        "message_drop_rate": drop_rate,
        "auth_rate": auth_rate,
        "subscribe_rate": sub_rate,
        "disconnects_by_reason": disconnects_by_reason,
        "level": level,
    }


def get_k8s_health():
    """
    Kubernetes cluster health via Prometheus recording rules.
    Level: Failed pods > 0 or restarts > 200 → critical; restarts > 50 or CPU > 80% → warning.
    """
    cpu_r = _vector("avg(cluster:node_cpu:ratio_rate5m) * 100")
    cpu_pct = round(float(cpu_r[0]["value"][1]), 2) if cpu_r else None

    restarts_r = _vector("sum(kube_pod_container_status_restarts_total)")
    total_restarts = int(float(restarts_r[0]["value"][1])) if restarts_r else 0

    phase_r = _vector("sum by(phase)(kube_pod_status_phase)")
    pod_phases = {
        r["metric"].get("phase", "unknown"): int(float(r["value"][1]))
        for r in phase_r
    }

    mem_r = _vector('sum(container_memory_working_set_bytes{container!=""})')
    memory_used_bytes = int(float(mem_r[0]["value"][1])) if mem_r else None

    failed = pod_phases.get("Failed", 0)
    if failed > 0 or total_restarts > 200:
        level = "critical"
    elif total_restarts > 50 or (cpu_pct is not None and cpu_pct > 80):
        level = "warning"
    else:
        level = "good"

    return {
        "cluster_cpu_pct": cpu_pct,
        "total_pod_restarts": total_restarts,
        "pod_phases": pod_phases,
        "memory_used_bytes": memory_used_bytes,
        "level": level,
    }


def get_redis_health():
    """
    Redis health from Redis Overview dashboard via Prometheus.
    Level: hit_rate_pct < 50% → warning; memory_used_pct > 80% → warning.
    """
    clients_r = _vector("sum(redis_connected_clients)")
    connected_clients = int(float(clients_r[0]["value"][1])) if clients_r else 0

    ops_r = _vector("sum(rate(redis_commands_total[5m]))")
    ops_rate = round(float(ops_r[0]["value"][1]), 2) if ops_r else 0.0

    # Use raw counters for hit rate (rate() gives 0 in low-traffic periods)
    hits_r = _vector("sum(redis_keyspace_hits_total)")
    misses_r = _vector("sum(redis_keyspace_misses_total)")
    hits = float(hits_r[0]["value"][1]) if hits_r else 0.0
    misses = float(misses_r[0]["value"][1]) if misses_r else 0.0
    hit_rate_pct = round(hits / (hits + misses) * 100, 2) if (hits + misses) > 0 else None

    mem_used_r = _vector("sum(redis_memory_used_bytes)")
    mem_max_r = _vector("sum(redis_memory_max_bytes)")
    memory_used_bytes = int(float(mem_used_r[0]["value"][1])) if mem_used_r else None
    memory_max_bytes = int(float(mem_max_r[0]["value"][1])) if mem_max_r else None
    memory_used_pct = (
        round(memory_used_bytes / memory_max_bytes * 100, 2)
        if memory_used_bytes and memory_max_bytes and memory_max_bytes > 0
        else None
    )

    level = "good"
    if hit_rate_pct is not None and hit_rate_pct < 50:
        level = "warning"
    if memory_used_pct is not None and memory_used_pct > 80:
        level = "warning"

    return {
        "connected_clients": connected_clients,
        "ops_rate_per_sec": ops_rate,
        "hit_rate_pct": hit_rate_pct,
        "memory_used_bytes": memory_used_bytes,
        "memory_max_bytes": memory_max_bytes,
        "memory_used_pct": memory_used_pct,
        "level": level,
    }


def get_mongodb_health():
    """
    MongoDB health from MongoDB Overview dashboard via Prometheus.
    ops_rate_per_sec is None if mongodb_mongod_op_counters_total is absent in Prometheus.
    Level: avg_latency_ms > 100 → warning.
    """
    up_r = _vector("sum(mongodb_up)")
    instances_up = int(float(up_r[0]["value"][1])) if up_r else 0

    try:
        ops_r = _vector("sum(rate(mongodb_mongod_op_counters_total[5m]))")
        ops_rate = round(float(ops_r[0]["value"][1]), 2) if ops_r else None
    except (IndexError, KeyError):
        ops_rate = None

    try:
        lat_total_r = _vector("sum(mongodb_mongod_op_latencies_latency_total)")
        lat_ops_r = _vector("sum(mongodb_mongod_op_latencies_ops_total)")
        lat_total = float(lat_total_r[0]["value"][1]) if lat_total_r else None
        lat_ops = float(lat_ops_r[0]["value"][1]) if lat_ops_r else None
        avg_latency_ms = (
            round(lat_total / lat_ops / 1000, 3)
            if lat_total is not None and lat_ops and lat_ops > 0
            else None
        )
    except (IndexError, KeyError):
        avg_latency_ms = None

    level = "warning" if avg_latency_ms is not None and avg_latency_ms > 100 else "good"

    return {
        "instances_up": instances_up,
        "ops_rate_per_sec": ops_rate,
        "avg_latency_ms": avg_latency_ms,
        "level": level,
    }


def get_mysql_health():
    """
    MySQL health from MySQL Overview dashboard via Prometheus.
    Level: slow_queries > 0 → warning; threads_connected > 100 → warning.
    """
    up_r = _vector("sum(mysql_up)")
    instances_up = int(float(up_r[0]["value"][1])) if up_r else 0

    qps_r = _vector("sum(rate(mysql_global_status_queries[5m]))")
    qps = round(float(qps_r[0]["value"][1]), 2) if qps_r else 0.0

    threads_r = _vector("sum(mysql_global_status_threads_connected)")
    threads_connected = int(float(threads_r[0]["value"][1])) if threads_r else 0

    slow_r = _vector("sum(mysql_global_status_slow_queries)")
    slow_queries = int(float(slow_r[0]["value"][1])) if slow_r else 0

    if slow_queries > 0 or threads_connected > 100:
        level = "warning"
    else:
        level = "good"

    return {
        "instances_up": instances_up,
        "qps": qps,
        "threads_connected": threads_connected,
        "slow_queries": slow_queries,
        "level": level,
    }


def get_linux_node_health():
    """
    Linux node health from CPU and system [linux-node-integration] dashboard via Prometheus.
    Level: CPU > 85% or disk > 90% → critical; CPU > 70% or disk > 80% or memory > 85% → warning.
    """
    cpu_r = _vector(
        '(1 - avg(rate(node_cpu_seconds_total{mode="idle"}[5m]))) * 100'
    )
    cpu_pct = round(float(cpu_r[0]["value"][1]), 2) if cpu_r else None

    mem_r = _vector(
        "( 1 - avg(node_memory_MemAvailable_bytes / node_memory_MemTotal_bytes) ) * 100"
    )
    memory_pct = round(float(mem_r[0]["value"][1]), 2) if mem_r else None

    disk_r = _vector(
        'avg(1 - node_filesystem_avail_bytes{mountpoint="/"}'
        ' / node_filesystem_size_bytes{mountpoint="/"}) * 100'
    )
    disk_pct = round(float(disk_r[0]["value"][1]), 2) if disk_r else None

    net_r = _vector("sum(rate(node_network_receive_bytes_total[5m]))")
    network_receive_bytes_per_sec = round(float(net_r[0]["value"][1]), 2) if net_r else None

    if (cpu_pct is not None and cpu_pct > 85) or (disk_pct is not None and disk_pct > 90):
        level = "critical"
    elif (
        (cpu_pct is not None and cpu_pct > 70)
        or (disk_pct is not None and disk_pct > 80)
        or (memory_pct is not None and memory_pct > 85)
    ):
        level = "warning"
    else:
        level = "good"

    return {
        "cpu_usage_pct": cpu_pct,
        "memory_usage_pct": memory_pct,
        "disk_usage_pct": disk_pct,
        "network_receive_bytes_per_sec": network_receive_bytes_per_sec,
        "level": level,
    }

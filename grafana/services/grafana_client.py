def get_rabbitmq_queue_backlog():
    """
    Panels from 'RabbitMQ Queue Backlog' dashboard (uid=afl7kc08i70g0d).
    Level proxy for Bo_chi_so 'Queue Backlog' (Ingestion / Core):
      good     = total_messages == 0
      warning  = 1 <= total_messages < 100
      critical = total_messages >= 100
    """
    total_result = _vector("sum(rabbitmq_queue_messages)")
    total = int(float(total_result[0]["value"][1])) if total_result else 0

    per_queue_result = _vector("sum by(queue)(rabbitmq_queue_messages)")
    queues = sorted(
        [
            {"queue": r["metric"].get("queue", "unknown"), "messages": int(float(r["value"][1]))}
            for r in per_queue_result
        ],
        key=lambda q: q["messages"],
        reverse=True,
    )

    if total == 0:
        level = "good"
    elif total < 100:
        level = "warning"
    else:
        level = "critical"

    return {
        "total_messages": total,
        "queues": queues,
        "level": level,
    }


def get_rabbitmq_throughput(queue=".+"):
    """
    Panels from 'RabbitMQ Orchestration Throughput' dashboard (uid=dflthsv5mt05cd).
    Returns publish rate, ack rate, and lag_rate (publish - ack; positive = backpressure).
    """
    publish_result = _vector(
        f'sum(rate(rabbitmq_queue_messages_published_total{{queue=~"{queue}"}}[1m]))'
    )
    ack_result = _vector(
        f'sum(rate(rabbitmq_queue_messages_acked_total{{queue=~"{queue}"}}[1m]))'
    )

    publish_rate = float(publish_result[0]["value"][1]) if publish_result else 0.0
    ack_rate = float(ack_result[0]["value"][1]) if ack_result else 0.0

    return {
        "publish_rate_per_sec": round(publish_rate, 6),
        "ack_rate_per_sec": round(ack_rate, 6),
        "lag_rate": round(publish_rate - ack_rate, 6),
        "queue_filter": queue,
    }


